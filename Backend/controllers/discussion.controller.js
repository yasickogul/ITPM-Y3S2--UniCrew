// Like/Unlike discussion
exports.likeDiscussion = async (req, res) => {
  try {
    const { id } = req.params;
    const { 'x-user-id': userId } = req.headers;

    const discussion = await Discussion.findById(id);
    if (!discussion) {
      return res.status(404).json({
        success: false,
        error: 'Discussion not found',
      });
    }

    const userLiked = discussion.likedBy.includes(userId);

    if (userLiked) {
      // Unlike
      discussion.likes -= 1;
      discussion.likedBy = discussion.likedBy.filter((id) => id !== userId);
    } else {
      // Like
      discussion.likes += 1;
      discussion.likedBy.push(userId);
    }

    await discussion.save();

    res.status(200).json({
      success: true,
      message: userLiked ? 'Discussion unliked' : 'Discussion liked',
      data: {
        likes: discussion.likes,
        liked: !userLiked,
      },
    });
  } catch (error) {
    console.error('Error liking discussion:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to like discussion',
    });
  }
};

