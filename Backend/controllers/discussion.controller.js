// Search discussions
exports.searchDiscussions = async (req, res) => {
  try {
    const { q, communityId, limit = 20 } = req.query;

    if (!q) {
      return res.status(400).json({
        success: false,
        error: 'Search query is required',
      });
    }

    const filter = {
      $or: [{ title: { $regex: q, $options: 'i' } }, { content: { $regex: q, $options: 'i' } }, { tags: { $regex: q, $options: 'i' } }],
    };

    if (communityId) {
      filter.communityId = communityId;
    }

    const results = await Discussion.find(filter).limit(parseInt(limit)).select({ comments: { $slice: 0 } });

    res.status(200).json({
      success: true,
      data: results,
      count: results.length,
    });
  } catch (error) {
    console.error('Error searching discussions:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to search discussions',
    });
  }
};

