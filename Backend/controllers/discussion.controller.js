/**
 * Discussion Controller
 * Handles all business logic for discussions and comments
 */

const Discussion = require('../models/discussion.model');
const {
  generateSmartTags,
  analyzeContentQuality,
  moderateContent,
} = require('../utils/aiService');

// Validation helpers
const validateTitle = (title) => {
  if (!title || title.trim().length < 5) {
    return 'Title must be at least 5 characters';
  }
  if (title.length > 200) {
    return 'Title must not exceed 200 characters';
  }
  return null;
};

const validateContent = (content) => {
  if (!content || content.trim().length < 10) {
    return 'Content must be at least 10 characters';
  }
  if (content.length > 5000) {
    return 'Content must not exceed 5000 characters';
  }
  return null;
};

const validateCategory = (category) => {
  const allowedCategories = [
    'Kuppi',
    'Programming',
    'Projects',
    'Events',
    'Career',
    'General',
    'Research',
    'Study Group',
    'Project',
    'Question',
    'Announcement',
    'Resource',
  ];
  if (!category || !allowedCategories.includes(category)) {
    return 'Invalid category selected';
  }
  return null;
};

const validateCommentContent = (content) => {
  if (!content || content.trim().length < 1) {
    return 'Comment cannot be empty';
  }
  if (content.length > 5000) {
    return 'Comment must not exceed 5000 characters';
  }
  return null;
};

// Create a new discussion
exports.createDiscussion = async (req, res) => {
  try {
    const { title, content, communityId, communityName, category, tags, images } = req.body;
    const { 'x-user-id': userId, 'x-user-name': userName } = req.headers;

    // Validation
    const titleError = validateTitle(title);
    if (titleError) {
      return res.status(400).json({ success: false, error: titleError });
    }

    const contentError = validateContent(content);
    if (contentError) {
      return res.status(400).json({ success: false, error: contentError });
    }

    const categoryError = validateCategory(category);
    if (categoryError) {
      return res.status(400).json({ success: false, error: categoryError });
    }

    if (!communityId || !communityName) {
      return res.status(400).json({ success: false, error: 'Community is required' });
    }

    // AI: Check content moderation in background
    const moderation = moderateContent(content, title);
    const isFlagged = moderation.severity >= 2; // High severity

    // AI: Generate smart tags if not provided
    let finalTags = tags && tags.length > 0 ? tags : generateSmartTags(title, content, category).slice(0, 10);

    // Create discussion
    const newDiscussion = new Discussion({
      title: title.trim(),
      content: content.trim(),
      images: images || [],
      author: userName || 'Anonymous',
      authorId: userId || 'unknown',
      communityId,
      communityName,
      category,
      tags: finalTags,
      status: isFlagged ? 'Flagged' : 'Open', // Flag if content issues detected
      aiAnalysis: {
        qualityScore: analyzeContentQuality(title, content).score,
        isFlagged,
        flagReasons: moderation.issues.map((i) => i.type),
      },
    });

    await newDiscussion.save();

    res.status(201).json({
      success: true,
      message: isFlagged ? 'Discussion created (flagged for review)' : 'Discussion created successfully',
      data: newDiscussion,
      aiInsights: {
        autoGeneratedTags: finalTags !== tags,
        isFlagged,
        flaggedReasons: moderation.issues,
      },
    });
  } catch (error) {
    console.error('Error creating discussion:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to create discussion',
    });
  }
};

// Get all discussions with filters, search, and pagination
exports.getDiscussions = async (req, res) => {
  try {
    const { communityId, category, search, status, sortBy = 'newest', page = 1, limit = 10 } = req.query;

    // Build filter object
    const filter = {};
    if (communityId) filter.communityId = communityId;
    if (category) filter.category = category;
    if (status) filter.status = status;

    // Search filter
    if (search) {
      filter.$or = [{ title: { $regex: search, $options: 'i' } }, { content: { $regex: search, $options: 'i' } }];
    }

    // Sort options
    const sortOptions = {};
    switch (sortBy) {
      case 'oldest':
        sortOptions.createdAt = 1;
        break;
      case 'mostCommented':
        sortOptions['comments.length'] = -1;
        break;
      case 'mostViewed':
        sortOptions.views = -1;
        break;
      case 'mostLiked':
        sortOptions.likes = -1;
        break;
      case 'newest':
      default:
        sortOptions.createdAt = -1;
    }

    // Pagination
    const pageNum = parseInt(page) || 1;
    const limitNum = parseInt(limit) || 10;
    const skip = (pageNum - 1) * limitNum;

    // Get total count for pagination
    const total = await Discussion.countDocuments(filter);
    const pages = Math.ceil(total / limitNum);

    // Fetch discussions
    const discussions = await Discussion.find(filter)
      .sort(sortOptions)
      .skip(skip)
      .limit(limitNum)
      .select({ comments: { $slice: 3 } }); // Limit comments in list view

    res.status(200).json({
      success: true,
      data: discussions,
      pagination: {
        total,
        page: pageNum,
        pages,
        limit: limitNum,
      },
    });
  } catch (error) {
    console.error('Error fetching discussions:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to fetch discussions',
    });
  }
};

// Get single discussion by ID
exports.getDiscussionById = async (req, res) => {
  try {
    const { id } = req.params;

    const discussion = await Discussion.findById(id);
    if (!discussion) {
      return res.status(404).json({
        success: false,
        error: 'Discussion not found',
      });
    }

    // Increment view count
    discussion.views += 1;
    const { 'x-user-id': userId } = req.headers;
    if (userId && !discussion.viewedBy.includes(userId)) {
      discussion.viewedBy.push(userId);
    }
    await discussion.save();

    res.status(200).json({
      success: true,
      data: discussion,
    });
  } catch (error) {
    console.error('Error fetching discussion:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to fetch discussion',
    });
  }
};

// Update discussion
exports.updateDiscussion = async (req, res) => {
  try {
    const { id } = req.params;
    const { title, content, category, tags, status } = req.body;
    const { 'x-user-id': userId } = req.headers;

    const discussion = await Discussion.findById(id);
    if (!discussion) {
      return res.status(404).json({
        success: false,
        error: 'Discussion not found',
      });
    }

    // Check authorization
    if (discussion.authorId !== userId) {
      return res.status(403).json({
        success: false,
        error: 'Only the author can edit this discussion',
      });
    }

    // Validate updates
    if (title) {
      const titleError = validateTitle(title);
      if (titleError) {
        return res.status(400).json({ success: false, error: titleError });
      }
      discussion.title = title.trim();
    }

    if (content) {
      const contentError = validateContent(content);
      if (contentError) {
        return res.status(400).json({ success: false, error: contentError });
      }
      discussion.content = content.trim();
    }

    if (category) {
      const categoryError = validateCategory(category);
      if (categoryError) {
        return res.status(400).json({ success: false, error: categoryError });
      }
      discussion.category = category;
    }

    if (tags) discussion.tags = tags;
    if (status) discussion.status = status;

    await discussion.save();

    res.status(200).json({
      success: true,
      message: 'Discussion updated successfully',
      data: discussion,
    });
  } catch (error) {
    console.error('Error updating discussion:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to update discussion',
    });
  }
};

